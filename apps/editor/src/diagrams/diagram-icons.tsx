/** How big the drawing is stored, in pixels; it is a vector, so only the ratio matters. */
export const ICON_PIXELS = 96;

/**
 * A neutral that reads on the light board and the dark one, for line icons on
 * an uncoloured box and for brand marks whose own colour is near black, or
 * light enough to fade into a pale box.
 */
export const ICON_NEUTRAL = '#64748b';

function luminance(hex: string): number {
  const value = Number.parseInt(hex, 16);
  const channel = (shift: number) => {
    const c = ((value >> shift) & 0xff) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(16) + 0.7152 * channel(8) + 0.0722 * channel(0);
}

function brandColor(hex: string): string {
  const light = luminance(hex);
  return light < 0.03 || light > 0.45 ? ICON_NEUTRAL : `#${hex}`;
}

/** Whether a name is drawn in its brand's colour, whatever box it is on. */
export function isBrandIcon(icon: DiagramIcon): boolean {
  return DRAWINGS[icon].kind === 'brand';
}

/**
 * The icon as a standalone SVG document, its line icons stroked in `color`.
 * Sized explicitly, since an SVG with no size decodes to nothing in some
 * browsers.
 */
export function iconSvg(icon: DiagramIcon, color: string): string {
  const drawing = DRAWINGS[icon];
  const open = `<svg xmlns="http://www.w3.org/2000/svg" width="${ICON_PIXELS}" height="${ICON_PIXELS}" viewBox="0 0 24 24"`;
  if (drawing.kind === 'brand') {
    return `${open}><path fill="${brandColor(drawing.icon.hex)}" d="${drawing.icon.path}"/></svg>`;
  }

  // Lucide draws through React; rendered once into a detached node and read
  // back, which costs nothing beyond the React already on the page.
  const host = document.createElement('div');
  const root = createRoot(host);
  const Icon = drawing.icon;
  flushSync(() => root.render(<Icon color={color} strokeWidth={1.75} />));
  const inner = host.querySelector('svg')?.innerHTML ?? '';
  root.unmount();
  return `${open} fill="none" stroke="${color}" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}
