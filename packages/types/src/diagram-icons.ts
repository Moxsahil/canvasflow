export type DiagramIconGroup = keyof typeof DIAGRAM_ICON_GROUPS;

export type DiagramIcon = (typeof DIAGRAM_ICON_GROUPS)[DiagramIconGroup][number];

export const DIAGRAM_ICONS: readonly DiagramIcon[] = Object.values(DIAGRAM_ICON_GROUPS).flat();

const ICON_NAMES: ReadonlySet<string> = new Set(DIAGRAM_ICONS);

export function isDiagramIcon(value: unknown): value is DiagramIcon {
  return typeof value === 'string' && ICON_NAMES.has(value);
}

/**
 * The colours a generated diagram may give a box, a group or a piece of text.
 * Names rather than values, so a diagram reads the same in either theme and
 * the board decides what each name paints as.
 */
export const DIAGRAM_COLORS = [
  'gray',
  'blue',
  'green',
  'orange',
  'red',
  'purple',
  'yellow',
  'teal',
] as const;

export type DiagramColor = (typeof DIAGRAM_COLORS)[number];

export function isDiagramColor(value: unknown): value is DiagramColor {
  return typeof value === 'string' && (DIAGRAM_COLORS as readonly string[]).includes(value);
}
